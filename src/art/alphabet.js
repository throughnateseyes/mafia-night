export const SPACE = 30;
export const TRACKING = 8;

/**
 * Lay out a string. Returns glyph centerlines with x offsets (em units),
 * and `fit` < 1 if it had to shrink to fit maxWidth.
 */
export function layoutText(str, { align = 'middle', maxWidth } = {}) {
  const chars = [...str.toUpperCase()];
  const items = [];
  let x = 0;
  for (const ch of chars) {
    if (ch === ' ') {
      x += SPACE;
      continue;
    }
    const g = GLYPHS[ch];
    if (!g) continue;
    items.push({ ch, d: g.d, x });
    x += g.w + TRACKING;
  }
  const width = Math.max(0, x - TRACKING);
  const fit = maxWidth && width > maxWidth ? maxWidth / width : 1;
  const shift = align === 'middle' ? -width / 2 : align === 'end' ? -width : 0;
  for (const it of items) it.x += shift;
  return { items, width, fit };
}
